/// `None` when the character is no digit, or its value is not below `radix`.
pub fn digit(c: char, radix: u32) -> Option<u32> {
    let cp = c as u32;
    let value = if let Some(&(lo, _)) = DIGIT
        .iter()
        .find(|&&(lo, hi)| (lo as u32..=hi as u32).contains(&cp))
    {
        cp - lo as u32
    } else {
        match cp {
            0x41..=0x5a => cp - 0x41 + 10,
            0x61..=0x7a => cp - 0x61 + 10,
            0xff21..=0xff3a => cp - 0xff21 + 10,
            0xff41..=0xff5a => cp - 0xff41 + 10,
            _ => return None,
        }
    };
    (value < radix).then_some(value)
}

