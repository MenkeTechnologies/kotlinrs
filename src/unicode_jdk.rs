/// Whether `c` lies in one of the sorted, disjoint inclusive `table` ranges.
pub fn contains(table: &[(u16, u16)], c: char) -> bool {
    let Ok(c) = u16::try_from(c as u32) else {
        return false;
    };
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

