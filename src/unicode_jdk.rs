/// `Character.getNumericValue(c)`: the radix-36 digit value where there is one,
/// the [`NUMERIC`] entry otherwise, and `-1` for a character with no numeric
/// value.
pub fn numeric_value(c: char) -> i32 {
    if let Some(d) = digit(c, 36) {
        return d as i32;
    }
    let Ok(cp) = u16::try_from(c as u32) else {
        return -1;
    };
    NUMERIC
        .binary_search_by_key(&cp, |&(k, _)| k)
        .map_or(-1, |at| NUMERIC[at].1)
}

